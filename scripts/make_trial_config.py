#!/usr/bin/env python3
"""Generate an aic_engine config with N randomized trials, for recording varied demos.

    python3 scripts/make_trial_config.py --trials 20 --seed 1 --out data/configs/demos_s1_n20.yaml

Starts from AIC's sample_config.yaml (scoring topics, limits, robot home, distractor mounts) and
randomizes what the official sample/eval configs vary:
  - task board x, y and yaw (ranges cover sample_config and eval_config)
  - SFP trials: 1-2 NIC cards on random rails, random rail offset; target sfp_port_0 or _1 on one
  - SC trials: SC mounts on one or both SC rails, random rail offset; target one of them
`--sc-fraction` sets the share of SC trials (default 1/3, like the qualification phase).
"""

import argparse
import copy
import math
import random
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SAMPLE = ROOT / "external/aic/aic_engine/config/sample_config.yaml"


def board_pose(rng, template):
    pose = dict(template)
    pose["x"] = round(rng.uniform(0.14, 0.21), 4)
    pose["y"] = round(rng.uniform(-0.22, 0.06), 4)
    # Mostly facing the robot (yaw ~ pi, as in sample/eval), sometimes rotated like eval trial_3.
    yaw = rng.uniform(math.pi - 0.25, math.pi + 0.25) if rng.random() < 0.8 else rng.uniform(-1.95, -1.65)
    pose["yaw"] = round(math.atan2(math.sin(yaw), math.cos(yaw)), 4)
    return pose


def rail(present, name=None, translation=0.0, yaw=0.0):
    if not present:
        return {"entity_present": False}
    return {"entity_present": True, "entity_name": name,
            "entity_pose": {"translation": round(translation, 4), "roll": 0.0, "pitch": 0.0, "yaw": yaw}}


def make_trial(rng, sfp_t, sc_t, limits, sc_trial):
    trial = copy.deepcopy(sc_t if sc_trial else sfp_t)
    board = trial["scene"]["task_board"]
    board["pose"] = board_pose(rng, board["pose"])
    task = next(iter(trial["tasks"].values()))
    nic_lim, sc_lim = limits["nic_rail"], limits["sc_rail"]

    nic_rails = rng.sample(range(5), rng.choice([1, 1, 2]) if not sc_trial else rng.choice([0, 1, 2]))
    for i in range(5):
        board[f"nic_rail_{i}"] = rail(i in nic_rails, f"nic_card_{i}",
                                      rng.uniform(nic_lim["min_translation"], nic_lim["max_translation"]))
    sc_rails = [0, 1] if (sc_trial and rng.random() < 0.5) else ([rng.choice([0, 1])] if sc_trial else [0])
    for i in range(2):
        board[f"sc_rail_{i}"] = rail(i in sc_rails, f"sc_mount_{i}",
                                     rng.uniform(sc_lim["min_translation"], sc_lim["max_translation"]),
                                     rng.choice([0.0, 0.1]))
    if sc_trial:
        target = rng.choice(sc_rails)
        task["target_module_name"] = f"sc_port_{target}"
    else:
        target = rng.choice(nic_rails)
        task["target_module_name"] = f"nic_card_mount_{target}"
        task["port_name"] = rng.choice(["sfp_port_0", "sfp_port_1"])
    return trial


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--trials", type=int, default=20)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--sc-fraction", type=float, default=1 / 3)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()

    base = yaml.safe_load(SAMPLE.read_text())
    sfp_t, sc_t = base["trials"]["trial_1"], base["trials"]["trial_3"]
    rng = random.Random(args.seed)
    n_sc = round(args.trials * args.sc_fraction)
    kinds = [True] * n_sc + [False] * (args.trials - n_sc)
    rng.shuffle(kinds)
    base["trials"] = {f"trial_{i + 1}": make_trial(rng, sfp_t, sc_t, base["task_board_limits"], sc)
                      for i, sc in enumerate(kinds)}
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(f"# Generated by scripts/make_trial_config.py --trials {args.trials} --seed {args.seed}\n"
                        + yaml.safe_dump(base, sort_keys=False))
    print(f"{args.out}: {args.trials} trials ({n_sc} SC, {args.trials - n_sc} SFP), seed {args.seed}")


if __name__ == "__main__":
    main()
